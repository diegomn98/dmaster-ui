/** Semantic color of the tabs (HeroUI-style). */
export type DmTabsColor = 'default' | 'primary' | 'secondary' | 'success' | 'warning' | 'danger';

/** Visual variant of the tablist. */
export type DmTabsVariant = 'solid' | 'bordered' | 'light' | 'underlined' | 'segment';

/** Size scale. */
export type DmTabsSize = 'sm' | 'md' | 'lg';

/** Corner rounding. `full` is pill-shaped. Ignored by the `underlined` variant. */
export type DmTabsRadius = 'none' | 'sm' | 'md' | 'lg' | 'full';

/** Where the tablist sits relative to the panels. */
export type DmTabsPlacement = 'top' | 'start';
